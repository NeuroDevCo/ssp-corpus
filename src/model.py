from dataclasses import dataclass, asdict
from multiprocessing import cpu_count
from pathlib import Path

from cmdstanpy import CmdStanModel, CmdStanMCMC
import numpy as np
import polars as pl

from src import utils


@dataclass
class Conf:
    seed: int = 1234
    iter_sampling: int = 1_000
    iter_warmup: int = 1_000
    chains: int = cpu_count() // 3
    parallel_chains: int = cpu_count() // 3
    adapt_delta: float | None = None
    step_size: float | None = None
    output_dir: Path | str | None = None


def get_ssp_stan_data(x: pl.DataFrame, names: bool = True) -> dict:
    """Transform syllables dataset into Stan data.

    Args:
        syllables: Syllables dataset, as generated by `get_syllables`.

    """
    data = x.group_by("iso639p3code").agg(
        y=pl.col("is_ssp").sum(),
        n=pl.len(),
        prop=pl.col("is_ssp").mean(),
    )
    j = data["iso639p3code"].cast(pl.Categorical).to_physical() + 1
    n = data["n"].to_list()
    y = [int(i) for i in data["y"].to_list()]
    N = len(set(data["iso639p3code"]))
    out = {"N": N, "y": y, "n": n, "j": j.to_list()}

    if names:
        out["j_names"] = data["iso639p3code"].to_list()

    return out


def get_freq_stan_data(x: pl.DataFrame, names: bool = True) -> dict:
    """Transform syllables dataset into Stan data.

    Args:
        syllables: Syllables dataset, as generated by `get_syllables`.

    """
    freq = [0.5 if ssp else -0.5 for ssp in x["is_ssp"]]
    j = x["iso639p3code"].cast(pl.Categorical).to_physical() + 1
    J = len(set(x["iso639p3code"]))
    y = [float(i) for i in x["freq"].to_list()]
    N = len(x)
    out = {"N": N, "J": J, "y": y, "x": freq, "j": j.to_list()}

    if names:
        out["j_names"] = x["iso639p3code"].to_list()

    return out


def fit_model(stan_data: dict, stan_file: Path | str, conf: Conf = Conf(), **kwargs):
    model = CmdStanModel(stan_file=str(stan_file))

    if conf.output_dir:
        Path(conf.output_dir).mkdir(exist_ok=True)
        conf.output_dir = str(conf.output_dir)

    model_settings = asdict(conf)
    data = stan_data.copy()
    data.pop("j_names")

    samples = model.sample(data=data, **model_settings, **kwargs)
    return model, samples


def get_posterior(
    samples: CmdStanMCMC,
    params: str | list[str] | None = None,
    group_names: list[str] | None = None,
):
    if params is None:
        params = []

    df = samples.summary()
    df.index.name = "param"
    df.reset_index(inplace=True)
    df = pl.from_pandas(df)

    target_cols = {"50%": "median", "5%": "lower", "95%": "upper", "R_hat": "rhat"}

    post = df.select(["param"] + list(target_cols.keys())).rename(target_cols)

    if params:
        if isinstance(params, list):
            params = "|".join(params)
        post = post.filter(pl.col("param").str.contains(params))

    if group_names is not None:
        idx = list(range(len(group_names)))
        param_name = [f"theta_j[{j + 1}]" for j in idx]
        lookup = {n: g for n, g in zip(param_name, group_names)}
        post = post.with_columns(
            pl.col("param").replace_strict(
                lookup, default=pl.col("param").alias("param_name")
            )
        )

    return post


def hdi(x, prob: float = 0.95):
    """Compute the 95% Highest Density Interval (HDI) for a numpy array."""
    # Sort the array
    arr_sorted = np.sort(x)
    n = len(arr_sorted)

    # Number of points to include in the interval
    n_interval = int(np.floor(prob * n))

    # Slide a window of size n_interval and find the one with the smallest range
    min_range = np.inf
    hdi_interval = (np.nan, np.nan)

    for i in range(n - n_interval + 1):
        current_range = arr_sorted[i + n_interval - 1] - arr_sorted[i]
        if current_range < min_range:
            min_range = current_range
            hdi_interval = (arr_sorted[i], arr_sorted[i + n_interval - 1])

    return hdi_interval


def main():

    # fit SSP model
    s = pl.read_parquet(utils.OUT_PATH / "syllables.parquet")
    stan_data = get_ssp_stan_data(s, names=True)
    _, samples = fit_model(stan_data, Path("model/ssp/ssp.stan"))
    samples.draws_pd().to_parquet(Path("model/ssp/ssp.parquet"))
    post_ssp = get_posterior(samples, group_names=stan_data["j_names"])
    post_ssp.write_parquet(utils.OUT_PATH / "posterior_ssp.parquet")

    # fit FREQ-SUBTLEX model
    s = pl.read_parquet(utils.OUT_PATH / "syllables_freq_subtlex.parquet")
    stan_data = get_freq_stan_data(s, names=True)
    _, samples = fit_model(stan_data, Path("model/freq_subtlex/freq.stan"))
    samples.draws_pd().to_parquet(Path("model/freq_subtlex/freq_subtlex.parquet"))
    post_freq = get_posterior(samples, group_names=stan_data["j_names"])
    post_freq.write_parquet(utils.OUT_PATH / "posterior_freq_subtlex.parquet")

    # fit FREQ-CHILDES model
    s = pl.read_parquet(utils.OUT_PATH / "syllables_freq_childes.parquet")
    stan_data = get_freq_stan_data(s, names=True)
    _, samples = fit_model(stan_data, Path("model/freq_childes/freq.stan"))
    samples.draws_pd().to_parquet(Path("model/freq_childes/freq_childes.parquet"))
    post_freq = get_posterior(samples, group_names=stan_data["j_names"])
    post_freq.write_parquet(utils.OUT_PATH / "posterior_freq_childes.parquet")

    return post_ssp, post_freq


if __name__ == "__main__":
    post_ssp, post_freq = main()
