from dataclasses import dataclass, asdict
from multiprocessing import cpu_count
from pathlib import Path

from cmdstanpy import CmdStanModel, CmdStanMCMC
import numpy as np
import polars as pl


@dataclass
class Conf:
    seed: int = 1234
    iter_sampling: int = 1_000
    iter_warmup: int = 1_000
    chains: int = cpu_count() // 3
    parallel_chains: int = cpu_count() // 3
    adapt_delta: float | None = None
    step_size: float | None = None
    output_dir: Path | str | None = None


def get_stan_data(x: pl.DataFrame) -> dict:
    """Transform syllables dataset into Stan data.

    Args:
        syllables: Syllables dataset, as generated by `get_syllables`.

    """
    freqs_zipf = x["freq"]
    freqs = x["freq"] - x["freq"].median()
    j = x["iso639p3code"].cast(pl.Categorical).to_physical() + 1
    y = [int(i) for i in x["is_ssp"].to_list()]
    n_j = len(set(x["iso639p3code"]))

    return {
        "N": len(x),
        "J": n_j,
        "y": y,
        "j": j.to_list(),
        "x": freqs.to_list(),
        "freq": freqs_zipf.to_list(),
    }


def fit_model(
    stan_data: dict,
    stan_file: Path | str = Path("model/model.stan"),
    conf: Conf = Conf(),
):
    model = CmdStanModel(stan_file=str(stan_file))

    if conf.output_dir:
        Path(conf.output_dir).mkdir(exist_ok=True)
        conf.output_dir = str(conf.output_dir)

    model_settings = asdict(conf)

    return model, model.sample(data=stan_data, **model_settings)


def synth_data(
    n: int = 20, j: int = 4, theta: float = 0.9, sigma_mu: float = 0.1, beta: float = 0
):
    x = np.random.normal(0, 0.5, n)
    groups = np.array(range(1, j + 1))
    groups = np.hstack([groups, np.random.randint(1, j + 1, n - j)])
    np.random.shuffle(groups)

    mu = np.random.normal(0, sigma_mu, j)
    mu_dict = {int(k): v for k, v in zip(range(1, j + 1), mu)}

    beta_1 = np.log(theta / (1 - theta))
    beta_2 = beta

    theta_i = []
    for ji, xi in zip(groups, x):
        logit = (beta_1 + mu_dict.get(int(ji), 0)) + (beta_2 * xi)
        theta_i.append(np.exp(logit) / (1 + np.exp(logit)))

    y = np.random.binomial(1, theta_i)
    data = {"N": n, "J": j, "j": groups, "y": y, "x": x}

    params = {
        "beta_1": float(beta_1),
        "beta_2": float(beta_2),
        "mu": [float(i) for i in list(mu_dict.values())],
        "sigma_mu": sigma_mu,
    }
    return data, params


def get_posterior(samples: CmdStanMCMC, params: str | list[str] | None = None):
    if params is None:
        params = []

    df = samples.summary()
    df.index.name = "param"
    df.reset_index(inplace=True)
    df = pl.from_pandas(df)

    target_cols = {"50%": "median", "5%": "lower", "95%": "upper", "R_hat": "rhat"}

    post = df.select(["param"] + list(target_cols.keys())).rename(target_cols)

    if params:
        if isinstance(params, list):
            params = "|".join(params)
        post = post.filter(pl.col("param").str.contains(params))

    return post


def get_epreds(
    samples: CmdStanMCMC, data: dict, n_draws: int = 50, scale: str = "prob"
):

    if scale not in ("logit", "prob"):
        raise ValueError("scale must be 'logit' or 'prob'")

    draws_beta = samples.stan_variable("beta")  # [chains, draws, 2]
    draws_mu = samples.stan_variable("mu")  # [chains, draws, J]

    n_samples = len(draws_beta)
    if n_draws < n_samples:
        draw_idx = np.random.randint(0, n_samples - 1, n_draws)
        draws_beta = draws_beta[draw_idx]
        draws_mu = draws_mu[draw_idx]

    # new x values
    n_vals = len(data["x"])
    n_samples = len(draws_beta)
    x_new = data["x"]
    X_new = np.vstack([np.ones_like(x_new), x_new])

    out = []
    for mu_j in draws_mu.T:
        mu_mat = np.stack([np.zeros(n_samples), mu_j])
        mu = np.repeat(np.expand_dims(mu_mat.T, 0), n_vals, 0)
        X = np.repeat(np.expand_dims(X_new, 2), n_samples, 2)
        beta = np.repeat(np.expand_dims(draws_beta, 0), n_vals, 0)

        p = np.sum((beta + mu) * X.transpose(1, 2, 0), 2)

        if scale == "prob":
            p = np.exp(p) / (1 + np.exp(p))

        out.append(p)

    return np.stack(out)


