"""Fit Bayesian models using PyMC."""

from pathlib import Path

import numpy as np
import polars as pl
import pymc as pm

from src import utils


def get_data(x: pl.DataFrame) -> dict:
    """Prepare data for Bayesian modelling.

    Args:
        x (pl.DataFrame): Syllables dataframe, as generated by `syllables.get_syllables()`.

    Returns:
        dict: Response variable, predictors, and index variables.
    """
    l = x["iso639p3code"].cast(pl.Categorical)

    return {
        "y": x["is_ssp"].to_numpy().astype(np.int32),
        "x": x["freq"].to_numpy(),
        "j": l.to_physical().to_numpy().astype(np.int32),
        "j_names": l.unique().sort().to_numpy(),
        "N": x.shape[0],
        "J": l.n_unique(),
    }


def fit_model(x: pl.DataFrame, **kwargs):
    """Fit Bayesian model with frequency as predictor.

    Args:
        x (pl.DataFrame): Syllables dataframe, as generated by `syllables.get_syllables()`.
        **kwargs: Additional arguments passed to `pm.sample()`.

    Returns:
        tuple[pm.Model, xr.DataTree]: Model and inference data of the model (comparible with Arviz).
    """
    data = get_data(x)
    coords = {"j": data["j_names"], "i": np.arange(data["N"])}
    x = (data["x"] - data["x"].mean()) / data["x"].std()  # Standardize
    y, j = data["y"], data["j"]

    with pm.Model(coords=coords) as model:
        # global intercept and slope
        α = pm.Normal("α", mu=0, sigma=1)
        β = pm.Normal("β", mu=0, sigma=1)

        # random intercepts (non-centered)
        u_σ = pm.HalfNormal("u_σ", sigma=0.5)
        u_z = pm.Normal("u_z", mu=0, sigma=1, dims="j")
        u = pm.Deterministic("u", u_z * u_σ, dims="j")

        # random slopes (non-centered)
        w_σ = pm.HalfNormal("w_σ", sigma=0.5)
        w_z = pm.Normal("w_z", mu=0, sigma=1, dims="j")
        w = pm.Deterministic("w", w_z * w_σ, dims="j")

        # linear predictor
        μ = pm.Deterministic("μ", α + u[j] + (β + w[j]) * x, dims="i")

        # likelihood
        pm.Bernoulli("y", p=pm.math.sigmoid(μ), observed=y, dims="i")

        # sampling
        idata = pm.sample(**kwargs)
        pm.compute_log_likelihood(idata)

    return model, idata


def main(path: Path, **kwargs):
    """Run models."""
    data = pl.read_parquet(path / "syllables.parquet")

    _, idata = fit_model(data, **kwargs)

    idata.to_netcdf(path / "post.nc")

    return idata


if __name__ == "__main__":
    for path in [utils.RESULTS_PATH, utils.RESULTS_PATH / "no-flat"]:
        main(path=path, target_accept=0.99, draws=2000, tune=2000, chains=8, cores=8)
