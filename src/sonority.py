"""Preprocess Wiktionary corpora."""

from functools import lru_cache
from itertools import groupby
from pathlib import Path
import polars as pl
import numpy as np
from panphon import FeatureTable, sonority
from rich.progress import track


FT = FeatureTable()
S = sonority.Sonority()
SON = {s: S.sonority(s) for s in FT.seg_dict if s.strip()}


def count_vocalic_clusters(x: str) -> int:
    """Count the number of vocalic clusters in a phonological word form.

    For instance, "CVVC" has one vocalic cluster, while "CVCV" has two vocalic clusters.

    Args:
        x (str): Syllabic structure to analyse.

    Returns:
        int: Number of vocalic clusters.
    """
    return len([b for a, b in groupby(x) if a == "V"])


def is_bitonic(x: np.array) -> bool:
    """Check if an array is bi-tonic (only has one maximum).

    Args:
        x (np.array): Array to evaluate.

    Returns:
        bool: True if the array is bitonic, False otherwise.
    """
    d = np.diff(x)
    return np.sum(np.sign(d[1:]) != np.sign(d[:-1])) < 2


def get_syll_structure(x: str) -> str:
    """Classify syllabic structure.

    Args:
        x (str): Phonological form of the syllable to classify in IPA formant.

    Returns:
        str: Syllabic structure, with consonants (C) and vowels (V).
    """
    struct = ""
    for s in FT.word_fts(x):
        if s.data["cons"] == 1:
            struct += "C"
        else:
            struct += "V"
    return struct


def get_syll_sonority(x: str) -> list[int]:
    """Get sonority score (1-9) of the segments of a syllable.

    Args:
        x (str): Phonological form of the syllable to score in IPA formant.

    Returns:
        list[int]: Sonority scores of each segment in the syllable.
    """
    return [SON[s] for s in x if s in SON]


def eval_ssp(x: list[int] | np.ndarray) -> bool:
    """Evaluate if sonority contour follows the Sonority Sequencing Principle (SSP).

    Args:
        x (list[int]): List of sonority scores, one for each segment.

    Returns:
        bool: True if the sonority contour follows SSP, False otherwise.
    """
    d = np.diff(np.array(x))
    return bool((d[: x.argmax()] >= 0).all() & (d[x.argmax() :] <= 0).all())


@lru_cache
def get_corpus(file: str) -> pl.DataFrame:
    """Get language corpus with syllabified forms and syllabic structures.

    Args:
        file (str): Raw data of the corpus, as generated by Wiktionary.

    Returns:
        pl.DataFrame: Processed corpus.
    """
    df = (
        pl.read_csv(file, separator="\t", has_header=False)
        .rename({"column_1": "word", "column_2": "phon"})
        .unique(pl.col("phon"))
        .with_columns(
            pl.col("phon")
            .str.replace_all(" ", "")
            .str.replace_all("ˈ", ".")
            .str.split(".")
        )
        .explode(pl.col("phon"))
        .with_columns(
            pl.col("phon")
            .map_elements(get_syll_structure, return_dtype=pl.String)
            .alias("struct")
        )
        .filter(
            pl.col("struct").map_elements(
                lambda x: count_vocalic_clusters(x) == 1, return_dtype=pl.Boolean
            )
        )
        .with_columns(
            pl.col("phon")
            .map_elements(get_syll_sonority, return_dtype=pl.List(pl.Int64))
            .alias("sonority"),
            pl.col("phon").str.len_chars().alias("n_phon"),
        )
        .with_columns(
            pl.col("sonority")
            .list.diff(null_behavior="drop")
            .map_elements(is_bitonic, return_dtype=pl.Boolean)
            .alias("is_ssp"),
        )
        .filter(pl.col("sonority") != [""])
    )

    return df


def main():
    """Main script."""
    path = Path("data", "processed")
    out = {}
    files = list(Path("data", "raw").glob("*.tsv"))
    for f in track(files, total=len(files)):
        lang = f.name.rsplit(".", maxsplit=1)[0]
        try:
            df = get_corpus(f)
            out[lang] = df
            file = Path(path / f"{lang}.csv")
            if len(df) < 3:
                df.with_columns(
                    pl.col("sonority").cast(pl.List(pl.String)).list.join(", ")
                ).write_csv(file)
        except pl.exceptions.NoDataError:
            print(f"Empty dataset for {lang}")
    return out


if __name__ == "__main__":
    DF = main()
